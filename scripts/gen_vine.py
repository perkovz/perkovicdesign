"""Generate src/content/vine.ts from the v3 design geometry (vine_geometry.py, from Figma v3p)."""
import json, math, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import vine_geometry as vine

def leafbase(at, i):
    f = (vine.FR[i] + vine.FR[i + 1]) / 2
    return at(f)[0]

def pack(d, L, nodes, leaves, at, W, H):
    return {
        "w": W, "h": H, "length": round(L, 2), "d": d,
        "nodes": [[round(x, 1), round(y, 1)] for x, y in nodes],
        "leaves": [{"d": lp, "vein": vp, "base": [round(b[0], 1), round(b[1], 1)]}
                   for (lp, vp), b in zip(leaves, [leafbase(at, i) for i in range(5)])],
    }

def horiz():
    fn = lambda t: (t, 282 + 24 * math.sin(2 * math.pi * (t - 40) / 430))
    d, L, at = vine.build(fn, 40, 1150)
    _, _, nodes, leaves = vine.vine(fn, 40, 1150, [-1, 1, -1, 1, -1])
    return pack(d, L, nodes, leaves, at, 1200, 540)

def vert(W, x0, y0, y1):
    fn = lambda t: (x0 + 7 * math.sin(2 * math.pi * (t - y0) / 380), t)
    d, L, at = vine.build(fn, y0, y1)
    _, _, nodes, leaves = vine.vine(fn, y0, y1, [1, -1, 1, -1, 1])
    return pack(d, L, nodes, leaves, at, W, int(y1 + 150))

out = {"desktop": horiz(), "tablet": vert(688, 64, 40, 1060), "mobile": vert(342, 34, 40, 1150)}
path = os.path.join(os.path.dirname(__file__), "..", "src", "content", "vine.ts")
with open(path, "w") as f:
    f.write("// Generated by scripts/gen_vine.py from the v3 Figma vine geometry. Do not edit by hand.\n")
    f.write("export const VINE_STOPS = %s as const;\n\n" % json.dumps(vine.FR))
    f.write("export type VineGeometry = {\n  w: number;\n  h: number;\n  length: number;\n  d: string;\n  nodes: [number, number][];\n  leaves: { d: string; vein: string; base: [number, number] }[];\n};\n\n")
    for k, v in out.items():
        f.write("export const VINE_%s: VineGeometry = %s;\n\n" % (k.upper(), json.dumps(v, indent=2)))
print({k: (v["length"], v["nodes"]) for k, v in out.items()})
